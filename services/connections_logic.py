import math


def generate_positions(
    usable_length,
    count,
    offset
):

    if count == 1:
        return [offset]

    step = usable_length / (count - 1)

    result = []

    for i in range(count):

        result.append(
            round(offset + step * i, 2)
        )

    return result

from services.connections_config import (
    CONNECTION_TYPES
)


# =====================================================
# CALCULATE CONNECTIONS
# =====================================================
#
# Функція рахує:
#
# 1. Кількість точок кріплення
# 2. Кількість фурнітури
# 3. Кількість свердлінь
#
# На основі:
#
# - довжини стику
# - типу з'єднання
#
# =====================================================


def calculate_connections(

    joint_length: int,

    connection_type: str
):

    # =================================================
    # ОТРИМУЄМО КОНФІГ ТЕХНОЛОГІЇ
    # =================================================

    config = CONNECTION_TYPES[
        connection_type
    ]

    # =================================================
    # БАЗОВІ ПАРАМЕТРИ
    # =================================================

    step = config["step"]

    edge_offset = config["edge_offset"]

    min_count = config["min_count"]

    min_length = config["min_length"]

    # =================================================
    # ПЕРЕВІРКА МІНІМАЛЬНОЇ ДОВЖИНИ
    # =================================================
    #
    # Якщо стик занадто малий,
    # таке з'єднання робити не можна
    #
    # =================================================

    if joint_length < min_length:

        return {

            "valid": False,

            "error": (
                f"Стик {joint_length} мм "
                f"замалий для "
                f"{connection_type}"
            )
        }

    # =================================================
    # РОБОЧА ДОВЖИНА
    # =================================================
    #
    # Від загальної довжини
    # віднімаємо відступи
    #
    # =================================================

    usable_length = (

        joint_length

        - edge_offset * 2
    )

    # =================================================
    # КІЛЬКІСТЬ ТОЧОК КРІПЛЕННЯ
    # =================================================
    #
    # Приклад:
    #
    # step = 400
    #
    # usable = 900
    #
    # 900 / 400 = 2.25
    #
    # ceil = 3
    #
    # +1 = 4 точки
    #
    # =================================================

    connections_count = (

        math.ceil(
            usable_length / step
        ) + 1
    )

    # =================================================
    # МІНІМУМ КРІПЛЕНЬ
    # =================================================

    connections_count = max(

        min_count,

        connections_count
    )

    # =================================================
    # ФУРНІТУРА
    # =================================================

    fittings = []

    for item in config["fittings"]:

        fittings.append({

            "code": item["code"],

            "qty": (
                item["qty"]
                * connections_count
            )
        })

    # =================================================
    # СВЕРДЛІННЯ
    # =================================================

    drilling = []

    for item in config["drilling"]:

        drilling.append({

            "type": item["type"],

            "diameter": item["diameter"],

            "qty": (
                item["qty"]
                * connections_count
            )
        })

    # =================================================
    # РЕЗУЛЬТАТ
    # =================================================

    return {

        # =============================================
        # ЧИ ВАЛІДНЕ З'ЄДНАННЯ
        # =============================================

        "valid": True,

        # =============================================
        # ТИП З'ЄДНАННЯ
        # =============================================

        "connection_type": connection_type,

        # =============================================
        # ДОВЖИНА СТИКУ
        # =============================================

        "joint_length": joint_length,

        # =============================================
        # РОБОЧА ДОВЖИНА
        # =============================================

        "usable_length": usable_length,

        # =============================================
        # КІЛЬКІСТЬ ТОЧОК
        # =============================================

        "connections_count": connections_count,

        # =============================================
        # ФУРНІТУРА
        # =============================================

        "fittings": fittings,

        # =============================================
        # СВЕРДЛІННЯ
        # =============================================

        "drilling": drilling,

        "positions": generate_positions(
            usable_length,
            connections_count,
            edge_offset
        )
    }
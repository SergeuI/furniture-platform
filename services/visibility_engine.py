# =====================================================
# VISIBILITY ENGINE
# Система видимості
# =====================================================

from services.cabinet_context_engine import (
    get_side_visibility
)

# =====================================================
# ВИДИМІ СТОРОНИ
# =====================================================

VISIBLE_RULES = {

    # =========================================
    # БОКОВИНИ
    # =========================================

    "side": {

        "visible": [

            "front"
        ]
    },

    # =========================================
    # ДНО
    # =========================================

    "bottom": {

        "visible": [

            "front"
        ]
    },

    # =========================================
    # КРИШКА
    # =========================================

    "top": {

        "visible": [

            "front"
        ]
    },

    # =========================================
    # ФАСАД
    # =========================================

    "facade": {

        "visible": [

            "top",

            "bottom",

            "left",

            "right"
        ]
    }
}


# =====================================================
# ОТРИМАТИ ВИДИМІ СТОРОНИ
# =====================================================

def get_visible_faces(
    part_type
):

    rules = VISIBLE_RULES.get(
        part_type,
        {}
    )

    return rules.get(
        "visible",
        []
    )


# =====================================================
# АВТО-КРАЙКА
# =====================================================

def create_visible_edge_map(

    part_type,

    edge="0.8",

    context=None,

    side=None
):

    edge_map = {

        "top": None,

        "bottom": None,

        "left": None,

        "right": None
    }

    # =========================================
    # БОКОВИНИ
    # =========================================

    if part_type == "side":

        visible = get_side_visibility(
            side,
            context
        )

    else:

        visible = get_visible_faces(
            part_type
        )

    # =========================================
    # APPLY
    # =========================================

    for face in visible:

        if face in edge_map:

            edge_map[face] = edge

    return edge_map
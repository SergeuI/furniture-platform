# =====================================================
# GLOBAL GAPS SYSTEM
# =====================================================

GAPS = {

    # =========================================
    # INSET FACADES
    # =========================================

    "inset": {

        "top": 2,

        "bottom": 2,

        "left": 2,

        "right": 2,

        "between_facades": 2
    },

    # =========================================
    # OVERLAY FACADES
    # =========================================

    "overlay": {

        "reveal": 2
    }
}


# =====================================================
# GET FACADE GAPS
# =====================================================

def get_facade_gaps(
    facade_type="inset"
):

    return GAPS.get(
        facade_type,
        GAPS["inset"]
    )
# =====================================================
# СИСТЕМА КООРДИНАТ ДЕТАЛЕЙ
# =====================================================

# Усі координати:
# x -> ширина
# y -> висота
# z -> глибина


# =====================================================
# СТВОРЕННЯ БАЗОВОЇ СИСТЕМИ КООРДИНАТ
# =====================================================

def create_coordinate_system():

    return {

        # Точка початку
        "origin": {

            "x": 0,
            "y": 0,
            "z": 0
        },

        # Напрямки осей
        "axis": {

            "x": "width",

            "y": "height",

            "z": "depth"
        }
    }


# =====================================================
# ДОДАТИ КООРДИНАТИ ДО ДЕТАЛІ
# =====================================================

def add_part_coordinates(
    part,
    x=0,
    y=0,
    z=0,
    rotation=0,
    plane="XY"
):

    part["position"] = {

        "x": round(x, 2),

        "y": round(y, 2),

        "z": round(z, 2)
    }

    # Поворот деталі
    part["rotation"] = rotation

    # Площина деталі
    part["plane"] = plane

    return part


# =====================================================
# КООРДИНАТИ ЛІВОЇ БОКОВИНИ
# =====================================================

def get_left_side_position():

    return {

        "x": 0,

        "y": 0,

        "z": 0
    }


# =====================================================
# КООРДИНАТИ ПРАВОЇ БОКОВИНИ
# =====================================================

def get_right_side_position(
    cabinet_width,
    thickness
):

    return {

        "x": (
            cabinet_width
            - thickness
        ),

        "y": 0,

        "z": 0
    }


# =====================================================
# КООРДИНАТИ ДНА
# =====================================================

def get_bottom_position(
    thickness
):

    return {

        "x": thickness,

        "y": 0,

        "z": 0
    }


# =====================================================
# КООРДИНАТИ КРИШКИ
# =====================================================

def get_top_position(
    cabinet_height,
    thickness
):

    return {

        "x": thickness,

        "y": (
            cabinet_height
            - thickness
        ),

        "z": 0
    }
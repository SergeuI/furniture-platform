# =====================================================
# СИСТЕМИ ОСЕЙ ДЛЯ ПЛОЩИН
# =====================================================

PLANE_AXIS = {

    # =========================================
    # XY
    # =========================================

    "XY": {

        "normal": "Z",

        "local_x": "X",

        "local_y": "Y"
    },

    # =========================================
    # XZ
    # =========================================

    "XZ": {

        "normal": "Y",

        "local_x": "X",

        "local_y": "Z"
    },

    # =========================================
    # YZ
    # =========================================

    "YZ": {

        "normal": "X",

        "local_x": "Y",

        "local_y": "Z"
    }
}


# =====================================================
# ОТРИМАТИ NORMAL AXIS
# =====================================================

def get_plane_normal(
    plane
):

    return PLANE_AXIS[
        plane
    ]["normal"]


# =====================================================
# ОТРИМАТИ LOCAL AXES
# =====================================================

def get_plane_axes(
    plane
):

    return PLANE_AXIS[
        plane
    ]


# =====================================================
# ТРАНСФОРМАЦІЯ LOCAL -> GLOBAL
# =====================================================

def transform_to_global(

    local_x,
    local_y,
    local_z,

    plane
):

    # =========================================
    # XY
    # =========================================

    if plane == "XY":

        return {

            "x": local_x,

            "y": local_y,

            "z": local_z
        }

    # =========================================
    # XZ
    # =========================================

    if plane == "XZ":

        return {

            "x": local_x,

            "y": local_z,

            "z": local_y
        }

    # =========================================
    # YZ
    # =========================================

    if plane == "YZ":

        return {

            "x": local_z,

            "y": local_x,

            "z": local_y
        }

    return {

        "x": local_x,

        "y": local_y,

        "z": local_z
    }


# =====================================================
# GLOBAL -> LOCAL
# =====================================================

def transform_to_local(

    global_x,
    global_y,
    global_z,

    plane
):

    # =========================================
    # XY
    # =========================================

    if plane == "XY":

        return {

            "x": global_x,

            "y": global_y,

            "z": global_z
        }

    # =========================================
    # XZ
    # =========================================

    if plane == "XZ":

        return {

            "x": global_x,

            "y": global_z,

            "z": global_y
        }

    # =========================================
    # YZ
    # =========================================

    if plane == "YZ":

        return {

            "x": global_y,

            "y": global_z,

            "z": global_x
        }

    return {

        "x": global_x,

        "y": global_y,

        "z": global_z
    }